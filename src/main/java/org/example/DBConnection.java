package org.example;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public final class DBConnection {

    private static String url = System.getenv().getOrDefault(
            "DB_URL",
            "jdbc:h2:./data/temperature_db"
    );

    private DBConnection() {
    }

    public static Connection get() throws SQLException {
        return DriverManager.getConnection(url, "sa", "");
    }

    static void setUrl(String newUrl) {
        url = newUrl;
    }

    public static void init() throws SQLException {
        try (
                Connection connection = get();
                Statement statement = connection.createStatement()
        ) {
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS temperature_unit (
                        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(20) NOT NULL,
                        symbol VARCHAR(1) UNIQUE NOT NULL
                    )
                    """);

            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS temp_record (
                        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        from_unit_id INT NOT NULL,
                        to_unit_id INT NOT NULL,
                        input_value DOUBLE PRECISION NOT NULL,
                        result_value DOUBLE PRECISION NOT NULL,
                        distance_km DOUBLE PRECISION NOT NULL,
                        time_hours DOUBLE PRECISION NOT NULL,
                        speed_kmh DOUBLE PRECISION NOT NULL,
                        FOREIGN KEY (from_unit_id)
                            REFERENCES temperature_unit(id),
                        FOREIGN KEY (to_unit_id)
                            REFERENCES temperature_unit(id)
                    )
                    """);

            statement.executeUpdate("""
                    MERGE INTO temperature_unit (name, symbol)
                    KEY (symbol)
                    VALUES ('Celsius', 'C')
                    """);

            statement.executeUpdate("""
                    MERGE INTO temperature_unit (name, symbol)
                    KEY (symbol)
                    VALUES ('Fahrenheit', 'F')
                    """);

            statement.executeUpdate("""
                    MERGE INTO temperature_unit (name, symbol)
                    KEY (symbol)
                    VALUES ('Kelvin', 'K')
                    """);
        }
    }
}